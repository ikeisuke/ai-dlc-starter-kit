# ----------------------------------------------------------------------
# gh_project_setup_env: 標準セットアップ
# ----------------------------------------------------------------------
# 副作用:
#   - AIDLC_REPO_ROOT を BATS_TEST_TMPDIR に固定
#   - .aidlc/cache / config を mkdir
#   - MOCK_DIR / GH_PROJECT_FIXTURE_DIR / GH_PROJECT_CALL_LOG を export
#   - PATH 先頭に MOCK_DIR を挿入
#   - GH_PROJECT_CALL_LOG を空ファイル化
gh_project_setup_env() {
    : "${BATS_TEST_TMPDIR:?BATS_TEST_TMPDIR must be set (run via bats)}"
    export AIDLC_REPO_ROOT="$BATS_TEST_TMPDIR"
    mkdir -p "$BATS_TEST_TMPDIR/.aidlc/cache" "$BATS_TEST_TMPDIR/config"

    export MOCK_DIR="${MOCK_DIR:-$BATS_TEST_TMPDIR/mock-bin}"
    mkdir -p "$MOCK_DIR"

    case ":$PATH:" in
        *":$MOCK_DIR:"*) ;;
        *) export PATH="$MOCK_DIR:$PATH" ;;
    esac

    export GH_PROJECT_FIXTURE_DIR="${GH_PROJECT_FIXTURE_DIR:-$BATS_TEST_TMPDIR/fixtures}"
    mkdir -p "$GH_PROJECT_FIXTURE_DIR"

    export GH_PROJECT_CALL_LOG="${GH_PROJECT_CALL_LOG:-$BATS_TEST_TMPDIR/gh_calls.log}"
    : > "$GH_PROJECT_CALL_LOG"
}

# ----------------------------------------------------------------------
# gh_project_mock_gh: gh wrapper factory
# ----------------------------------------------------------------------
# wrapper の動作:
#   1. CallLogEntry 追記
#   2. auth status 即応答
#   3. グローバル MOCK_GH_FAIL 評価
#   4. ApiSelector 別 case 文評価 (per-api MOCK_<API>_FAIL → fixture dispatch)
#   5. *) 未モック検出 exit 99
#   6. fixture cat / 不在 exit 98
gh_project_mock_gh() {
    cat > "$MOCK_DIR/gh" <<'GH_MOCK'
#!/usr/bin/env bash
# Auto-generated by gh_project_mock_gh. Do not edit.
printf '%s\n' "$*" >> "${GH_PROJECT_CALL_LOG:-/dev/null}"

# auth status は固定 stub
if [[ "$1" == "auth" ]] && [[ "$2" == "status" ]]; then
    echo "github.com"
    echo "  ✓ Logged in"
    echo "  - Token scopes: 'project', 'read:org', 'read:project'"
    exit 0
fi

# グローバル失敗注入 (全 API 共通 / per-api より優先)
if [[ -n "${MOCK_GH_FAIL:-}" ]]; then
    echo "gh mock: global injected failure" >&2
    exit 1
fi

# ApiSelector 別 dispatch (per-api 失敗注入 → fixture 解決)
# 失敗注入 + fixture 解決を 1 関数化 (per-API 用)
#   1) MOCK_<API>_FAIL=1: 即失敗
#   2) MOCK_<API>_FAIL_ON_NTH=N: 該当 API の累計 N 回目で失敗 (count は GH_PROJECT_CALL_LOG から派生)
_dispatch_api() {
    local key="$1"      # ApiSelector (例: "project list")
    local var_stem="$2" # 変数語幹 (例: PROJECT_LIST)
    local fixture="$3"  # fixture filename (例: project-list.json)
    local fail_var="MOCK_${var_stem}_FAIL"
    if [[ -n "${!fail_var:-}" ]]; then
        echo "gh mock: ${var_stem,,} injected failure" >&2
        exit 1
    fi
    local nth_var="MOCK_${var_stem}_FAIL_ON_NTH"
    if [[ -n "${!nth_var:-}" ]]; then
        # R2 #1 反映: 正規表現メタ文字非依存で行頭境界を保証するため awk index() を使用。
        # grep -F は固定文字列だが行頭アンカー不可、grep -E は正規表現メタ文字依存。
        # `index($0, k) == 1` で行頭プレフィックス一致を厳密判定する。
        local cnt
        cnt="$(awk -v k="${key} " 'index($0, k) == 1 { c++ } END { print c + 0 }' "${GH_PROJECT_CALL_LOG:-/dev/null}" 2>/dev/null || echo 0)"
        if [[ "$cnt" == "${!nth_var}" ]]; then
            echo "gh mock: ${var_stem,,} nth-call failure (call=$cnt)" >&2
            exit 1
        fi
    fi
    _f="${GH_PROJECT_FIXTURE_DIR}/${fixture}"
}

case "$1 $2" in
    "project list")         _dispatch_api "project list" "PROJECT_LIST" "project-list.json" ;;
    "project create")       _dispatch_api "project create" "PROJECT_CREATE" "project-create.json" ;;
    "project edit")         _dispatch_api "project edit" "PROJECT_EDIT" "project-edit.json" ;;
    "project field-list")   _dispatch_api "project field-list" "PROJECT_FIELD_LIST" "project-field-list.json" ;;
    "project field-create") _dispatch_api "project field-create" "PROJECT_FIELD_CREATE" "project-field-create.json" ;;
    "project view-list")    _dispatch_api "project view-list" "PROJECT_VIEW_LIST" "project-view-list.json" ;;
    "project view-create")  _dispatch_api "project view-create" "PROJECT_VIEW_CREATE" "project-view-create.json" ;;
    "project item-add")     _dispatch_api "project item-add" "PROJECT_ITEM_ADD" "project-item-add.json" ;;
    "project item-list")    _dispatch_api "project item-list" "PROJECT_ITEM_LIST" "project-item-list.json" ;;
    "project item-edit")    _dispatch_api "project item-edit" "PROJECT_ITEM_EDIT" "project-item-edit.json" ;;
    "issue list")           _dispatch_api "issue list" "ISSUE_LIST" "issue-list.json" ;;
    "issue view")           _dispatch_api "issue view" "ISSUE_VIEW" "issue-view.json" ;;
    "issue create")         _dispatch_api "issue create" "ISSUE_CREATE" "issue-create.json" ;;
    "issue edit")           _dispatch_api "issue edit" "ISSUE_EDIT" "issue-edit.json" ;;
    "issue close")          _dispatch_api "issue close" "ISSUE_CLOSE" "issue-close.json" ;;
    "issue delete")         _dispatch_api "issue delete" "ISSUE_DELETE" "issue-delete.json" ;;
    "api graphql")          _dispatch_api "api graphql" "API_GRAPHQL" "api-graphql.json" ;;
    *)
        echo "unmocked: $*" >&2
        exit 99 ;;
esac

# fixture 解決
if [[ ! -f "$_f" ]]; then
    echo "fixture not found: $_f" >&2
    exit 98
fi

# --jq 引数があれば fixture に対して jq を適用する (mock fidelity 改善)
# 期待呼出例: gh issue list --json url --jq '.[].url' / gh issue view --json body --jq '.body'
# R1 #2 反映: --jq 指定時は fixture が valid JSON であることを必須化し、parse 失敗時は
# 明示的に exit 97 (jq_fixture_invalid) として false-positive を排除する。raw text 出力が
# 必要な API (gh issue create など) は --jq を伴わない呼出のため、現状の cat フォールバックは
# --jq 未指定パスでのみ機能する。
_jq_expr=""
_prev=""
for _arg in "$@"; do
    if [[ "$_prev" == "--jq" ]]; then
        _jq_expr="$_arg"
        break
    fi
    _prev="$_arg"
done
if [[ -n "$_jq_expr" ]]; then
    if ! command -v jq >/dev/null 2>&1; then
        echo "gh mock: --jq specified but jq not installed" >&2
        exit 97
    fi
    if ! jq empty < "$_f" >/dev/null 2>&1; then
        echo "gh mock: --jq specified but fixture is not valid JSON: $_f" >&2
        exit 97
    fi
    jq -r "$_jq_expr" < "$_f"
else
    cat "$_f"
fi
GH_MOCK
    chmod +x "$MOCK_DIR/gh"
}

# ----------------------------------------------------------------------
# gh_project_mock_dasel: dasel wrapper (v2/v3 syntax 双方を吸収)
# ----------------------------------------------------------------------
gh_project_mock_dasel() {
    cat > "$MOCK_DIR/dasel" <<'DASEL_MOCK'
#!/usr/bin/env bash
# Auto-generated by gh_project_mock_dasel. Do not edit.
# 期待呼出: dasel -f <toml> <key> (v2) または dasel -i toml <key> < <toml> (v3)
_file=""
_key=""
while [[ $# -gt 0 ]]; do
    case "$1" in
        -f) _file="$2"; shift 2 ;;
        -i|-t|-v|-o|--type|--value) shift 2 ;;
        put) shift; while [[ $# -gt 0 ]] && [[ "$1" != -* ]]; do shift; done ;;
        *) _key="$1"; shift ;;
    esac
done
# fixture サイドカー: <toml>.json
if [[ -n "$_file" ]] && [[ -f "$_file.json" ]]; then
    # JSON から key 値を抽出 (jq があれば使い、無ければ素朴な grep)
    if command -v jq >/dev/null 2>&1; then
        jq -r ".${_key} // empty" "$_file.json"
    else
        cat "$_file.json"
    fi
elif [[ -t 0 ]] || [[ -n "$_key" ]]; then
    # stdin から読む v3 形式は最小限の対応 (現状は空を返す)
    :
fi
DASEL_MOCK
    chmod +x "$MOCK_DIR/dasel"
}

# ----------------------------------------------------------------------
# gh_project_mock_yq: yq wrapper (<file>.json を返す)
# ----------------------------------------------------------------------
gh_project_mock_yq() {
    cat > "$MOCK_DIR/yq" <<'YQ_MOCK'
#!/usr/bin/env bash
# Auto-generated by gh_project_mock_yq. Do not edit.
_file="${@: -1}"
if [[ -f "$_file.json" ]]; then
    cat "$_file.json"
else
    echo "yq mock: fixture not found: $_file.json" >&2
    exit 1
fi
YQ_MOCK
    chmod +x "$MOCK_DIR/yq"
}

# ----------------------------------------------------------------------
# gh_project_set_fixture: リポジトリ commit 対象 fixture をランタイム展開先にコピー
# ----------------------------------------------------------------------
# 使用例: gh_project_set_fixture project-list "${BATS_TEST_DIRNAME}/fixtures/project-list.json"
gh_project_set_fixture() {
    local api="$1"
    local src="$2"
    : "${GH_PROJECT_FIXTURE_DIR:?GH_PROJECT_FIXTURE_DIR not set (call gh_project_setup_env first)}"
    if [[ ! -f "$src" ]]; then
        echo "gh_project_set_fixture: source not found: $src" >&2
        return 1
    fi
    cp "$src" "${GH_PROJECT_FIXTURE_DIR}/${api}.json"
}

# ----------------------------------------------------------------------
# gh_project_inject_failure: per-api 失敗注入
# ----------------------------------------------------------------------
# 使用例: gh_project_inject_failure "project list"  # → MOCK_PROJECT_LIST_FAIL=1
#         gh_project_inject_failure "issue delete"  # → MOCK_ISSUE_DELETE_FAIL=1
# グローバル失敗は直接 export MOCK_GH_FAIL=1 を呼ぶ
gh_project_inject_failure() {
    local api="$1"
    local upper var
    # 半角スペース・ハイフンを _ に置換、小文字を大文字に
    upper="$(printf '%s' "$api" | tr '[:lower:] -' '[:upper:]__')"
    var="MOCK_${upper}_FAIL"
    export "$var=1"
}

# ----------------------------------------------------------------------
# gh_project_assert_gh_call_count: 呼出回数アサート (ERE: 正規表現を受け付ける)
# ----------------------------------------------------------------------
# 使用例: gh_project_assert_gh_call_count "^issue delete " 1
# コントラクト: pattern は POSIX 拡張正規表現 (`grep -E`)。`^` / `$` / `.` などのメタ文字を意図的に使う用途向け。
# 固定文字列マッチが必要な場合は gh_project_assert_gh_call_count_fixed を使うこと。
gh_project_assert_gh_call_count() {
    local pattern="$1"
    local expected="$2"
    : "${GH_PROJECT_CALL_LOG:?GH_PROJECT_CALL_LOG not set (call gh_project_setup_env first)}"
    local actual
    actual="$(grep -c -E "$pattern" "$GH_PROJECT_CALL_LOG" || true)"
    if [[ "$actual" -ne "$expected" ]]; then
        {
            echo "gh_project_assert_gh_call_count: expected $expected calls of pattern '$pattern', got $actual"
            echo "call log contents:"
            cat "$GH_PROJECT_CALL_LOG" || true
        } >&2
        return 1
    fi
}

# ----------------------------------------------------------------------
# gh_project_assert_gh_call_count_fixed: 固定文字列で行全体一致の呼出回数アサート
# ----------------------------------------------------------------------
# 使用例: gh_project_assert_gh_call_count_fixed "auth status" 1
# コントラクト: needle は固定文字列で**行全体一致** (`grep -Fx`)。部分一致による false-positive を防ぐ。
# 部分一致 / 行頭一致 / 正規表現が必要な場合は gh_project_assert_gh_call_count を使う。
gh_project_assert_gh_call_count_fixed() {
    local needle="$1"
    local expected="$2"
    : "${GH_PROJECT_CALL_LOG:?GH_PROJECT_CALL_LOG not set (call gh_project_setup_env first)}"
    local actual
    actual="$(grep -cFx -- "$needle" "$GH_PROJECT_CALL_LOG" || true)"
    if [[ "$actual" -ne "$expected" ]]; then
        {
            echo "gh_project_assert_gh_call_count_fixed: expected $expected calls of '$needle', got $actual"
            echo "call log contents:"
            cat "$GH_PROJECT_CALL_LOG" || true
        } >&2
        return 1
    fi
}

# ----------------------------------------------------------------------
# gh_project_assert_gh_call_contains: 呼出引数 grep アサート (ERE)
# ----------------------------------------------------------------------
# 使用例: gh_project_assert_gh_call_contains "project create.*--owner"
gh_project_assert_gh_call_contains() {
    local pattern="$1"
    : "${GH_PROJECT_CALL_LOG:?GH_PROJECT_CALL_LOG not set (call gh_project_setup_env first)}"
    if ! grep -q -E "$pattern" "$GH_PROJECT_CALL_LOG"; then
        {
            echo "gh_project_assert_gh_call_contains: no call matched pattern '$pattern'"
            echo "call log contents:"
            cat "$GH_PROJECT_CALL_LOG" || true
        } >&2
        return 1
    fi
}
